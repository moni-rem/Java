package selfStudy.Encapsulation;

public class Person {
    private String name;
    private int age;

    public String getName() {
        return name;
    }
    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }
    public int setAge(int age) {
         return this.age = age;
    }
}
